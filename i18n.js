  var LANGS = ['ru', 'uz', 'en'];
  var STORE_KEY = 'mmm-lang';
  var OG_LOCALE = { ru: 'ru_RU', uz: 'uz_UZ', en: 'en_US' };
  var listeners = [];

  function valid(l) { return LANGS.indexOf(l) !== -1 ? l : null; }

  function fromUrl() {
    try { return valid((new URLSearchParams(window.location.search).get('lang') || '').toLowerCase()); } catch (e) { return null; }
  }
  function fromStorage() {
    try { return valid(window.localStorage.getItem(STORE_KEY)); } catch (e) { return null; }
  }
  function fromBrowser() {
    var list = (navigator.languages && navigator.languages.length) ? navigator.languages : [navigator.language || ''];
    var code = String(list[0] || '').toLowerCase().slice(0, 2);
    if (code === 'uz') return 'uz';
    if (code === 'ru') return 'ru';
    return 'en';
  }

  var lang = fromUrl() || fromStorage() || fromBrowser();

  function lookup(l, key) {
    var d = DICT[l];
    if (d && Object.prototype.hasOwnProperty.call(d, key)) return d[key];
    if (Object.prototype.hasOwnProperty.call(DICT.ru, key)) return DICT.ru[key];
    return null;
  }
  function fill(s, params) {
    if (!params) return s;
    return s.replace(/\{(\w+)\}/g, function (m, k) { return k in params ? params[k] : m; });
  }

  // Перевод строки из JS: t('brief.step', { n: 2, total: 10 }) или t('ключ', null, 'ru')
  function t(key, params, l) {
    var s = lookup(l || lang, key);
    return s == null ? key : fill(s, params);
  }

  // 57.9 → «57,9» (RU, UZ) или «57.9» (EN)
  function num(v, digits, l) {
    var s = Number(v).toFixed(digits == null ? 1 : digits);
    return (l || lang) === 'en' ? s : s.replace('.', ',');
  }
  function moneyText(v, per, l) {
    l = l || lang;
    return num(v, 1, l) + ' ' + t('unit.mln', null, l) + (per ? ' ' + t('unit.per', null, l) : '');
  }
  function moneyHtml(v, per, l) {
    l = l || lang;
    return num(v, 1, l) + ' ' + t('unit.mln', null, l) + (per ? ' <small>' + t('unit.per', null, l) + '</small>' : '');
  }

  function each(root, sel, fn) {
    Array.prototype.forEach.call(root.querySelectorAll(sel), fn);
  }

  function apply(root) {
    root = root || document;
    each(root, '[data-i18n]', function (el) {
      var s = lookup(lang, el.getAttribute('data-i18n'));
      if (s != null) el.textContent = fill(s, { n: el.getAttribute('data-i18n-n') });
    });
    each(root, '[data-i18n-html]', function (el) {
      var s = lookup(lang, el.getAttribute('data-i18n-html'));
      if (s != null) el.innerHTML = fill(s, { n: el.getAttribute('data-i18n-n') });
    });
    ['placeholder', 'aria-label', 'alt', 'content'].forEach(function (attr) {
      each(root, '[data-i18n-' + attr + ']', function (el) {
        var s = lookup(lang, el.getAttribute('data-i18n-' + attr));
        if (s != null) el.setAttribute(attr, s);
      });
    });
    each(root, '[data-money]', function (el) {
      el.innerHTML = moneyHtml(parseFloat(el.getAttribute('data-money')), el.hasAttribute('data-money-per'));
    });
    each(root, '[data-num]', function (el) {
      el.textContent = num(parseFloat(el.getAttribute('data-num')));
    });
  }

  function render() {
    document.documentElement.lang = lang;
    var og = document.querySelector('meta[property="og:locale"]');
    if (og) og.setAttribute('content', OG_LOCALE[lang]);
    apply(document);
    each(document, '[data-set-lang]', function (btn) {
      var on = btn.getAttribute('data-set-lang') === lang;
      btn.setAttribute('aria-pressed', on ? 'true' : 'false');
      btn.classList.toggle('is-active', on);
    });
  }

  function setLang(l, remember) {
    l = valid(l);
    if (!l) return;
    var changed = l !== lang;
    lang = l;
    if (remember) {
      try { window.localStorage.setItem(STORE_KEY, l); } catch (e) { /* хранилище недоступно — просто не запоминаем */ }
      // Если в адресе был ?lang=, обновляем его, чтобы после перезагрузки остался выбранный язык
      try {
        var url = new URL(window.location.href);
        if (url.searchParams.has('lang')) {
          url.searchParams.set('lang', l);
          window.history.replaceState(null, '', url.toString());
        }
      } catch (e) { /* ignore */ }
    }
    render();
    if (changed) listeners.forEach(function (fn) { fn(lang); });
  }

  document.addEventListener('click', function (e) {
    var btn = e.target.closest('[data-set-lang]');
    if (btn) setLang(btn.getAttribute('data-set-lang'), true);
  });

  render();

  return {
    langs: LANGS,
    dict: DICT,
    lang: function () { return lang; },
    setLang: setLang,
    onChange: function (fn) { listeners.push(fn); },
    t: t,
    num: num,
    moneyText: moneyText,
    moneyHtml: moneyHtml,
    apply: apply
  };
